"""Shared Postgres durable tier for all stores (Supabase-friendly).

Role in the storage ladder: Redis (hot) -> Postgres (durable) -> SQLite
(disaster tier) -> memory (last resort). When ``DATABASE_URL`` is unset or
Postgres is unreachable this module returns ``None`` and every caller simply
behaves as it did before — SQLite, then memory.

Supabase notes:
- Use the session-mode/direct connection string (NOT the transaction-mode
  pooler on :6543) — transaction pooling breaks prepared statements and
  server-side cursors used by psycopg and LangGraph.
- ``prepare_threshold=0`` is set defensively for any pooled proxy.
- SSL is required: ``sslmode=require`` is appended when missing.

Usage:
    from pg_store import pg_fetchone, pg_execute

    row = await pg_fetchone("SELECT x FROM t WHERE k = $1", (key,))
    await pg_execute("INSERT INTO t (k, v) VALUES ($1, $2) ON CONFLICT (k) DO UPDATE SET v = $2", (k, v))
"""

from __future__ import annotations

